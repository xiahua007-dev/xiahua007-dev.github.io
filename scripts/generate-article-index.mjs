import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import frontMatter from 'front-matter'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const repoRoot = path.resolve(__dirname, '..')
const writingDir = path.join(repoRoot, 'content', 'writing')
const outputDir = path.join(repoRoot, 'src', 'generated')
const outputFile = path.join(outputDir, 'articlesIndex.js')

function slugFromFilename(filename) {
  return filename.replace(/\.md$/, '')
}

function normalizeDateValue(value) {
  if (value == null) return ''
  return String(value)
}

function getDateSortValue(value) {
  const normalized = normalizeDateValue(value)

  if (/^\d{4}-\d{2}-\d{2}$/.test(normalized)) {
    return Date.parse(`${normalized}T00:00:00Z`)
  }

  if (/^\d{4}-\d{2}$/.test(normalized)) {
    return Date.parse(`${normalized}-01T00:00:00Z`)
  }

  if (/^\d{4}$/.test(normalized)) {
    return Date.parse(`${normalized}-01-01T00:00:00Z`)
  }

  return Number.NEGATIVE_INFINITY
}

const files = fs.existsSync(writingDir)
  ? fs.readdirSync(writingDir).filter((file) => file.endsWith('.md'))
  : []

const articles = files
  .map((file) => {
    const raw = fs.readFileSync(path.join(writingDir, file), 'utf8')
    const { attributes } = frontMatter(raw)

    return {
      slug: slugFromFilename(file),
      title: attributes.title || slugFromFilename(file),
      category: attributes.category || '未分类',
      date: normalizeDateValue(attributes.date),
      status: attributes.status || '阅读全文',
      summary: attributes.summary || '',
    }
  })
  .sort((a, b) => {
    const dateDelta = getDateSortValue(b.date) - getDateSortValue(a.date)

    if (dateDelta !== 0) return dateDelta

    return a.title.localeCompare(b.title, 'zh-Hans-CN')
  })

fs.mkdirSync(outputDir, { recursive: true })
fs.writeFileSync(
  outputFile,
  `// This file is generated by scripts/generate-article-index.mjs.\nexport const articlesIndex = ${JSON.stringify(articles, null, 2)}\n`,
)
